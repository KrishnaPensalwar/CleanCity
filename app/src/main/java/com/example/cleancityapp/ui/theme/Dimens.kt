package com.example.cleancityapp.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Central spacing scale. Use instead of ad-hoc `.dp` literals so padding/gaps
 * stay consistent across screens.
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
}

/**
 * Central corner-radius scale for cards, chips, badges and buttons.
 */
object Radius {
    val badge = 8.dp
    val card = 12.dp
    val button = 16.dp
    val chip = 20.dp
    val large = 24.dp
}
